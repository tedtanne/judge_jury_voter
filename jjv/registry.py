"""The archetype registry: one place that knows every juror and every preset.

    from jjv.registry import get, panel, validate
    panel("Physics of Compute")      # -> list of archetype records
    validate()                       # -> [] when the registry is consistent

``python -m jjv.registry`` prints the catalog that lives at docs/archetypes.md, and
``python -m jjv.registry --readme`` refreshes the roster in README.md;
tests/test_registry.py fails if either drifts from the code.
"""

from __future__ import annotations

import sys

from jjv.archetypes import DEFAULT_ARCHETYPES
from jjv.domain_roles import DOMAIN_ROLES
from jjv.legends import LEGENDS, PRESET_PANELS
from jjv.nash import NASH_AGENT
from jjv.thinkers import GAP_ROLES, THINKERS

ALL_ARCHETYPES = [*DEFAULT_ARCHETYPES, *LEGENDS, *THINKERS, *DOMAIN_ROLES, *GAP_ROLES, NASH_AGENT]
BY_ID = {a["id"]: a for a in ALL_ARCHETYPES}

# The controlled vocabulary for veto dimensions. A Judge's finding must carry one of
# these strings in its ``dimension`` field for NashBroker to treat a blocker as credible.
# Add a word here deliberately, never by typo.
VETO_DIMENSIONS = {
    "security": "Exploitable vulnerabilities, authz, secrets, supply chain",
    "complexity": "Complexity that does not deserve to exist",
    "failure-handling": "Unhandled failure on a critical path",
    "experience": "An end-to-end experience not fit to ship",
    "mission-assurance": "Mission fitness and the assurance case",
    "attestation": "Verifiable provenance, identity and revocation",
    "crypto": "Cryptographic soundness",
    "privacy": "Re-identification and linkage exposure",
    "consensus-safety": "Safety of a consensus or replication protocol",
    "evidence": "Claims the evidence does not support",
    "physical-correctness": "Physical claims that are false at their stated scope",
    "cost-recovery": "Prices that cannot recover the asset's full cost",
}


def get(archetype_id: str) -> dict:
    try:
        return BY_ID[archetype_id]
    except KeyError:
        raise KeyError(f"unknown archetype id: {archetype_id!r}") from None


def panel(name: str) -> list[dict]:
    if name not in PRESET_PANELS:
        raise KeyError(f"unknown preset: {name!r}")
    return [get(i) for i in PRESET_PANELS[name]]


def validate() -> list[str]:
    """Every consistency rule the registry must satisfy. Empty list means healthy."""
    problems = []
    ids = [a["id"] for a in ALL_ARCHETYPES]
    for dup in sorted({i for i in ids if ids.count(i) > 1}):
        problems.append(f"duplicate id: {dup}")
    for a in ALL_ARCHETYPES:
        if a["veto"] != bool(a.get("veto_dimensions")):
            problems.append(f"{a['id']}: veto flag disagrees with veto_dimensions")
        for d in a.get("veto_dimensions", []):
            if d not in VETO_DIMENSIONS:
                problems.append(f"{a['id']}: veto dimension {d!r} not in VETO_DIMENSIONS")
        if a["role"] == "broker" and a["veto"]:
            problems.append(f"{a['id']}: a broker may not hold a veto")
    for name, members in PRESET_PANELS.items():
        for m in members:
            if m not in BY_ID:
                problems.append(f"preset {name!r}: unknown archetype {m!r}")
        if len(set(members)) != len(members):
            problems.append(f"preset {name!r}: repeated member")
        if not 3 <= len(members) <= 6:
            problems.append(f"preset {name!r}: {len(members)} members (want 3-6)")
    return problems


# ---------------------------------------------------------------------------
# Catalog (docs/archetypes.md)
# ---------------------------------------------------------------------------

def _row(a):
    veto = ", ".join(f"`{d}`" for d in a.get("veto_dimensions", [])) or "—"
    dims = "; ".join(f"{d['name']} ({d['weight']:g})" for d in a["rubric"]) or "— (author, unscored)"
    by = a.get("inspired_by") or ""
    by = f" · *inspired by {by}*" if by and (a in LEGENDS or a in THINKERS) else ""
    return f"| `{a['id']}` | {a['name']}{by} | {a['discipline']} | {a['weight']:g} | {veto} | {dims} |"


def catalog() -> str:
    head = "| id | Name | Discipline | Weight | Veto on | Rubric (weight) |\n|---|---|---|---|---|---|"
    out = [
        "# Archetype catalog",
        "",
        "Generated by `python -m jjv.registry > docs/archetypes.md`. Do not edit by hand:",
        "`tests/test_registry.py` fails when this file and the code disagree.",
        "",
        f"**{len(ALL_ARCHETYPES)} archetypes** ({len(DEFAULT_ARCHETYPES)} defaults, "
        f"{len(LEGENDS)} legends, {len(THINKERS)} thinkers, {len(DOMAIN_ROLES)} domain roles, "
        f"{len(GAP_ROLES)} gap roles, 1 broker) and "
        f"**{len(PRESET_PANELS)} preset panels**.",
        "",
        "Legends are trait profiles *inspired by* how notable people are publicly known to "
        "work. Thinkers are methods of reasoning inspired by historical thinkers. Neither are "
        "impersonations, and they imply no endorsement or affiliation.",
        "",
        "## Defaults (auto-convene by discipline)",
        "", head, *(_row(a) for a in DEFAULT_ARCHETYPES), "",
    ]
    cats = []
    for a in LEGENDS:
        if a["category"] not in cats:
            cats.append(a["category"])
    out += ["## Legends (join through presets)", ""]
    for c in cats:
        members = [a for a in LEGENDS if a["category"] == c]
        out += [f"### {c} ({len(members)})", "", head, *(_row(a) for a in members), ""]
    out += ["## Thinkers (join through presets)", "", head, *(_row(a) for a in THINKERS), "",
            "## Domain roles", "", head, *(_row(a) for a in DOMAIN_ROLES), "",
            "## Gap roles", "", head, *(_row(a) for a in GAP_ROLES), "",
            "## Broker", "", head, _row(NASH_AGENT), "",
            "## Veto dimensions", "", "| Dimension | Covers | Held by |", "|---|---|---|"]
    for d, desc in VETO_DIMENSIONS.items():
        holders = ", ".join(a["name"] for a in ALL_ARCHETYPES if d in a.get("veto_dimensions", []))
        out.append(f"| `{d}` | {desc} | {holders or '—'} |")
    out += ["", "## Preset panels", "", "| Preset | Members |", "|---|---|"]
    for name, members in PRESET_PANELS.items():
        out.append(f"| {name} | " + ", ".join(get(m)["name"] for m in members) + " |")
    return "\n".join(out) + "\n"


README_START = "<!-- roster:start (generated by python -m jjv.registry --readme) -->"
README_END = "<!-- roster:end -->"


def _readme_table(members, inspired: bool = False) -> list[str]:
    def judges(a):
        return "; ".join(d["name"] for d in a["rubric"]) or "Writes drafts; never votes"

    def veto(a):
        return ", ".join(f"`{d}`" for d in a.get("veto_dimensions", [])) or "—"

    if inspired:
        rows = ["| Archetype | Inspired by | Judges on | Veto |", "|---|---|---|---|"]
        rows += [f"| {a['name']} | {a.get('inspired_by') or '—'} | {judges(a)} | {veto(a)} |"
                 for a in members]
    else:
        rows = ["| Archetype | Judges on | Veto |", "|---|---|---|"]
        rows += [f"| {a['name']} | {judges(a)} | {veto(a)} |" for a in members]
    return rows


def _details(summary: str, body: list[str]) -> list[str]:
    return ["<details>", f"<summary><b>{summary}</b></summary>", "", *body, "", "</details>", ""]


def readme_roster() -> str:
    """The README's per-group roster, kept between README_START and README_END."""
    legends: list[str] = []
    cats: list[str] = []
    for a in LEGENDS:
        if a["category"] not in cats:
            cats.append(a["category"])
    for c in cats:
        members = [a for a in LEGENDS if a["category"] == c]
        legends += [f"**{c} ({len(members)})**", "", *_readme_table(members, inspired=True), ""]
    presets = ["| Preset | Members |", "|---|---|"]
    presets += [f"| {name} | " + ", ".join(get(m)["name"] for m in members) + " |"
                for name, members in PRESET_PANELS.items()]
    out = [
        README_START,
        "### Every archetype, by group",
        "",
        'Click a group to open it. "Judges on" lists the archetype\'s rubric dimensions, and '
        '"Veto" is the one area where its blocker is forced into the fix list.',
        "",
        *_details(f"Defaults ({len(DEFAULT_ARCHETYPES)}) — convene automatically by discipline",
                  _readme_table(DEFAULT_ARCHETYPES)),
        *_details(f"Legends ({len(LEGENDS)}) — trait profiles that join through presets",
                  legends[:-1]),
        *_details(f"Thinkers ({len(THINKERS)}) — methods of reasoning, no vetoes, "
                  "not yet run live", _readme_table(THINKERS)),
        *_details(f"Domain roles ({len(DOMAIN_ROLES)}) — specialists grounded in published "
                  "papers", _readme_table(DOMAIN_ROLES)),
        *_details(f"Gap roles ({len(GAP_ROLES)}) — areas nobody else covers, no vetoes, "
                  "not yet run live", _readme_table(GAP_ROLES)),
        *_details("Broker (1) — Nash_Agent", _readme_table([NASH_AGENT])),
        *_details(f"Presets ({len(PRESET_PANELS)}) — ready-made panels for `--panel`", presets),
        README_END,
    ]
    return "\n".join(out)


def sync_readme(text: str) -> str:
    """Return README text with the roster block replaced by the current one."""
    start, end = text.find(README_START), text.find(README_END)
    if start < 0 or end < start:
        raise ValueError("README has no roster markers")
    return text[:start] + readme_roster() + text[end + len(README_END):]


if __name__ == "__main__":
    problems = validate()
    if problems:
        print("\n".join(problems), file=sys.stderr)
        sys.exit(1)
    if sys.argv[1:] == ["--readme"]:
        from pathlib import Path

        readme = Path(__file__).resolve().parents[1] / "README.md"
        readme.write_text(sync_readme(readme.read_text(encoding="utf-8")), encoding="utf-8")
    else:
        sys.stdout.write(catalog())
